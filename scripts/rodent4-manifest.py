#!/usr/bin/env python3
"""The files of Rodent IV that ChessPenguin downloads from the authors' repository
(personalities and opening books, docs/decisions.md «Rodent IV»), with sizes and SHA-256,
written as apps/desktop/src/rodent4_files.rs.

    git clone https://github.com/nescitus/rodent-iv /tmp/rodent-iv
    git -C /tmp/rodent-iv checkout <COMMIT>
    python3 -I scripts/rodent4-manifest.py /tmp/rodent-iv
"""
import hashlib
import os
import subprocess
import sys

repo = sys.argv[1]
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
commit = subprocess.run(["git", "-C", repo, "rev-parse", "HEAD"], capture_output=True, text=True, check=True).stdout.strip()
files = []
for top in ("personalities", "books"):
    for dirpath, _, names in os.walk(os.path.join(repo, top)):
        for n in sorted(names):
            path = os.path.join(dirpath, n)
            rel = os.path.relpath(path, repo).replace(os.sep, "/")
            # Chess960 is not played here.
            if rel.endswith("guide_960.bin"):
                continue
            data = open(path, "rb").read()
            files.append((rel, len(data), hashlib.sha256(data).hexdigest()))
files.sort()
out = [
    "//! Generated by scripts/rodent4-manifest.py: the personalities and opening books of",
    "//! Rodent IV as they are in the authors' repository at `COMMIT`, with their sizes and",
    "//! SHA-256 (each is checked as it is downloaded).",
    "",
    f'pub const COMMIT: &str = "{commit}";',
    "",
    "/// (path in the repository, bytes, SHA-256).",
    "pub const FILES: &[(&str, u64, &str)] = &[",
]
out += [f'    ("{p}", {s}, "{h}"),' for p, s, h in files]
out += ["];", ""]
open(os.path.join(root, "apps", "desktop", "src", "rodent4_files.rs"), "w").write("\n".join(out))
print(len(files), "files,", sum(s for _, s, _ in files) // 1_000_000, "MB, commit", commit)
