//! UI translations. The English text is the key; missing entries fall back to English.

use std::collections::HashMap;
use std::fmt::Display;
use std::sync::OnceLock;
use std::sync::atomic::{AtomicU8, Ordering};

use serde::{Deserialize, Serialize};

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Serialize, Deserialize, Default)]
pub enum Lang {
    #[default]
    En,
    Ru,
    Fr,
    De,
    Es,
    It,
}

impl Lang {
    pub const ALL: [Lang; 6] = [Lang::En, Lang::Ru, Lang::Fr, Lang::De, Lang::Es, Lang::It];

    /// Native language name.
    pub fn label(self) -> &'static str {
        match self {
            Lang::En => "English",
            Lang::Ru => "Русский",
            Lang::Fr => "Français",
            Lang::De => "Deutsch",
            Lang::Es => "Español",
            Lang::It => "Italiano",
        }
    }

    fn column(self) -> usize {
        self as usize
    }

    /// The first supported language among the system's preferred ones ("uk-UA, ru-RU"
    /// gives Russian), or English.
    pub fn from_locales<S: AsRef<str>>(locales: impl IntoIterator<Item = S>) -> Lang {
        locales
            .into_iter()
            .find_map(|l| {
                // "ru-RU", "ru_RU.UTF-8", "de-CH", "es-419", "fr".
                let code = l
                    .as_ref()
                    .split(['-', '_', '.', '@'])
                    .next()?
                    .to_ascii_lowercase();
                match code.as_str() {
                    "en" => Some(Lang::En),
                    "ru" => Some(Lang::Ru),
                    "fr" => Some(Lang::Fr),
                    "de" => Some(Lang::De),
                    "es" => Some(Lang::Es),
                    "it" => Some(Lang::It),
                    _ => None,
                }
            })
            .unwrap_or_default()
    }

    /// The language of this system (see [`Lang::from_locales`]).
    pub fn system() -> Lang {
        Lang::from_locales(sys_locale::get_locales())
    }
}

static CURRENT: AtomicU8 = AtomicU8::new(0);

pub fn set_lang(lang: Lang) {
    CURRENT.store(lang as u8, Ordering::Relaxed);
}

pub fn current() -> Lang {
    Lang::ALL
        .get(CURRENT.load(Ordering::Relaxed) as usize)
        .copied()
        .unwrap_or_default()
}

fn table() -> &'static HashMap<&'static str, &'static [&'static str; 6]> {
    static MAP: OnceLock<HashMap<&'static str, &'static [&'static str; 6]>> = OnceLock::new();
    MAP.get_or_init(|| ROWS.iter().map(|row| (row[0], row)).collect())
}

/// Translates an English UI string into the current language.
pub fn tr(key: &'static str) -> &'static str {
    let lang = current();
    if lang == Lang::En {
        return key;
    }
    table()
        .get(key)
        .map(|row| row[lang.column()])
        .unwrap_or(key)
}

/// "1 game", "5 games" in the interface language, with Russian plural forms
/// ("1 партия", "3 партии", "5 партий").
pub fn games(n: usize) -> String {
    let num = crate::large_db::grouped(n);
    match current() {
        Lang::Ru => {
            let word = match (n % 10, n % 100) {
                (1, x) if x != 11 => "партия",
                (2..=4, x) if !(12..=14).contains(&x) => "партии",
                _ => "партий",
            };
            format!("{num} {word}")
        }
        Lang::En => format!("{num} {}", if n == 1 { "game" } else { "games" }),
        Lang::Fr => format!("{num} {}", if n <= 1 { "partie" } else { "parties" }),
        Lang::De => format!("{num} {}", if n == 1 { "Partie" } else { "Partien" }),
        Lang::Es => format!("{num} {}", if n == 1 { "partida" } else { "partidas" }),
        Lang::It => format!("{num} {}", if n == 1 { "partita" } else { "partite" }),
    }
}

/// "11,7 млн партий" / "267 партий": a database size in a short form.
pub fn games_short(n: usize) -> String {
    if n >= 1_000_000 {
        let short = crate::large_db::short_count(n);
        let word = match current() {
            Lang::Ru => "партий",
            Lang::En => "games",
            Lang::Fr => "parties",
            Lang::De => "Partien",
            Lang::Es => "partidas",
            Lang::It => "partite",
        };
        format!("{short} {word}")
    } else {
        games(n)
    }
}

/// Translates and substitutes `{name}` placeholders.
pub fn trf(key: &'static str, args: &[(&str, &dyn Display)]) -> String {
    let mut s = tr(key).to_string();
    for (name, value) in args {
        s = s.replace(&format!("{{{name}}}"), &value.to_string());
    }
    s
}

