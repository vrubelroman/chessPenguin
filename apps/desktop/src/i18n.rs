    #[test]
    fn system_language() {
        assert_eq!(Lang::from_locales(["ru-RU"]), Lang::Ru);
        assert_eq!(Lang::from_locales(["ru_RU.UTF-8"]), Lang::Ru);
        assert_eq!(Lang::from_locales(["uk-UA", "ru-RU", "en-US"]), Lang::Ru);
        assert_eq!(Lang::from_locales(["de-CH"]), Lang::De);
        assert_eq!(Lang::from_locales(["es-419"]), Lang::Es);
        assert_eq!(Lang::from_locales(["fr"]), Lang::Fr);
        assert_eq!(Lang::from_locales(["it_IT@euro"]), Lang::It);
        assert_eq!(Lang::from_locales(["en-GB", "ru-RU"]), Lang::En);
        assert_eq!(Lang::from_locales(["ja-JP", "pt-BR"]), Lang::En);
        assert_eq!(Lang::from_locales(["C"]), Lang::En);
        assert_eq!(Lang::from_locales(Vec::<String>::new()), Lang::En);
    }

    /// Every `tr("…")` / `trf("…"` key used in the sources must have a translation row.
    #[test]
    fn all_used_keys_are_translated() {
        let sources = [
            include_str!("app.rs"),
            include_str!("assets.rs"),
            include_str!("analysis.rs"),
            include_str!("game_view.rs"),
            include_str!("library.rs"),
            include_str!("large_db.rs"),
            include_str!("board_search.rs"),
            include_str!("engine_offer.rs"),
            include_str!("notation.rs"),
            include_str!("review.rs"),
            include_str!("engines.rs"),
            include_str!("examples.rs"),
            include_str!("settings.rs"),
            include_str!("settings_ui.rs"),
            include_str!("widgets.rs"),
            include_str!("reference.rs"),
            include_str!("report.rs"),
            include_str!("board.rs"),
            include_str!("engine_download.rs"),
            include_str!("main.rs"),
        ];
        let mut missing = Vec::new();
        let mut found = 0;
        for src in sources {
            for marker in ["tr(", "trf("] {
                for (i, _) in src.match_indices(marker) {
                    // Skip identifiers that merely end in `tr` (e.g. `str(`).
                    let prev = src[..i].chars().next_back();
                    if prev.is_some_and(|c| c.is_alphanumeric() || c == '_') {
                        continue;
                    }
                    // rustfmt may move the literal to the next line.
                    let rest = src[i + marker.len()..].trim_start();
                    let Some(rest) = rest.strip_prefix('"') else {
                        continue;
                    };
                    let Some(end) = rest.find('"') else { continue };
                    found += 1;
                    let key = &rest[..end];
                    if !table().contains_key(key) {
                        missing.push(key.to_string());
                    }
                }
            }
        }
        assert!(found > 100, "scanner found only {found} keys");
        assert!(missing.is_empty(), "untranslated keys: {missing:?}");
    }

    #[test]
    fn rows_are_unique_and_complete() {
        let mut seen = std::collections::HashSet::new();
        for row in ROWS {
            assert!(seen.insert(row[0]), "duplicate key {}", row[0]);
            assert!(
                row.iter().all(|s| !s.is_empty()),
                "empty cell in {}",
                row[0]
            );
        }
    }
